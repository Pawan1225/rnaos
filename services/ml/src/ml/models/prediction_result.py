"""
RNAOS prediction result model.
"""

from __future__ import annotations

from dataclasses import dataclass

from ml.constants import (
    PREDICTION_TARGETS,
)


@dataclass(slots=True, frozen=True)
class PredictionResult:
    """
    Immutable machine learning prediction.

    Stores the predictions generated by a trained
    machine learning model together with confidence
    estimates and experiment metadata.
    """

    folding_difficulty: float

    expected_mfe: float

    structural_stability: float

    solver_suitability: float

    runtime_estimation: float

    optimization_complexity: float

    confidence_score: float

    model_name: str

    experiment_id: str

    prediction_timestamp: str

    @property
    def prediction_count(
        self,
    ) -> int:
        """
        Number of biological prediction targets.
        """

        return len(
            PREDICTION_TARGETS,
        )
